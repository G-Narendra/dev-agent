    def get_all_roles(self) -> list[str]:
        """Get list of all available roles from the skills folder."""
        if self._all_roles_cache:
            return self._all_roles_cache
        
        roles_dir = os.path.join(self.skills_path, "roles")
        if not os.path.isdir(roles_dir):
            return []
        
        roles = []
        for item in os.listdir(roles_dir):
            item_path = os.path.join(roles_dir, item)
            if os.path.isdir(item_path):
                roles.append(item)
        
        self._all_roles_cache = sorted(roles)
        return self._all_roles_cache
    
